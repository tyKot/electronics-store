# Часто задаваемые вопросы

## Доставка

### Какие способы доставки доступны?
Мы предлагаем несколько способов доставки:
- **Курьерская доставка** по Москве и Санкт-Петербургу — 1-2 рабочих дня
- **СДЭК** — доставка по всей России за 3-7 рабочих дней
- **Почта России** — в любой населённый пункт за 5-14 дней
- **Самовывоз** из пунктов выдачи в крупных городах

Бесплатная доставка предоставляется при заказе от 50 000 ₽.

### Сколько стоит доставка?
- Курьер по Москве/СПб: 500 ₽ (бесплатно от 50 000 ₽)
- СДЭК: от 300 ₽ в зависимости от региона
- Почта России: от 250 ₽
- Самовывоз: бесплатно

## Оплата

### Как можно оплатить заказ?
Доступны следующие способы оплаты:
- **Банковская карта** (Visa, MasterCard, МИР) при оформлении онлайн
- **СБП** (Система быстрых платежей) — мгновенная оплата
- **Электронные кошельки** — ЮMoney, QIWI
- **Наличные** при получении курьеру
- **Безналичный расчёт** для юридических лиц

### Можно ли оформить рассрочку?
Да, мы предлагаем рассрочку 0-0-12 от банков-партнёров:
- Тинькофф
- Альфа-Банк
- Сбербанк

Оформление онлайн за 5 минут. Доступна для заказов от 10 000 ₽.

## Гарантия и возврат

### Какая гарантия на товары?
- Официальная гарантия производителя от 1 до 3 лет
- 14 дней на возврат товара надлежащего качества
- Обращение по гарантии — по чеку или номеру заказа

### Как вернуть товар?
- В течение 14 дней с момента покупки
- Товар не должен быть в использовании
- Сохранён товарный вид и упаковка
- Возврат средств — 3-5 рабочих дней
- Технически сложные товары возвращаются только при наличии брака

## Заказы

### Как отследить заказ?
- Трек-номер приходит на email после отправки
- Статус можно узнать в личном кабинете
- Через наш чат-бот по номеру заказа
- Курьер свяжется за час до доставки

